def chunk(typ, data):
    c = struct.pack(">I", len(data)) + typ + data
    return c + struct.pack(">I", zlib.crc32(typ + data) & 0xFFFFFFFF)


def write_png(path, pixels, w, h):
    raw = b"".join(b"\x00" + bytes(pixels[y * w * 3:(y + 1) * w * 3]) for y in range(h))
    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(raw, 9))
    png += chunk(b"IEND", b"")
    with open(path, "wb") as f:
        f.write(png)


def main():
    pixels = bytearray([255] * (W * H * 3))

    def px(x, y, col):
        if 0 <= x < W and 0 <= y < H:
            i = (y * W + x) * 3
            pixels[i:i + 3] = bytes(col)

    def rect(x, y, w, h, col):
        for yy in range(y, y + h):
            for xx in range(x, x + w):
                px(xx, yy, col)

    def text(x, y, s, scale, col):
        cx = x
        for ch in s.upper():
            glyph = FONT.get(ch, FONT[" "])
            for r in range(7):
                for c in range(5):
                    if glyph[r][c] == "1":
                        for dy in range(scale):
                            for dx in range(scale):
                                px(cx + c * scale + dx, y + r * scale + dy, col)
            cx += 6 * scale

    # Header
    rect(0, 0, W, 150, NAVY)
    text(40, 28, "24 NOVEMBER 2026", 4, WHITE)
    text(40, 96, "WORLD NEWS IN ONE IMAGE", 3, (200, 210, 230))

    y = 180
    for idx, (tag, headline) in enumerate(HEADLINES):
        rect(40, y, 12, 110, ACCENTS[idx])
        text(70, y, tag, 2, ACCENTS[idx])
        lines = textwrap.wrap(headline, width=62)
        ly = y + 32
        for line in lines[:2]:
            text(70, ly, line, 2, BLACK)
            ly += 34
        y += 128

    text(40, 960, "SUMMARY OF 24 NOVEMBER 2026 - PUBLIC NEWS REPORTS", 2, GREY)

    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    write_png(OUTPUT, pixels, W, H)


if __name__ == "__main__":
    main()
